def region_of(venue):
    """경기장 이름 → 지역. 모르면 '미분류'."""
    v = (venue or "").strip()
    if not v:
        return "미정"
    if v in EXACT:
        return EXACT[v]
    for key, reg in KEYWORDS:
        if key in v:
            return reg
    return "미분류"


